/**
 * @file fs_utils.h
 * @brief Утилиты для работы с файловой системой.
 *
 * Содержит функции для определения расположения исполняемого файла
 * и преобразования путей.
 */
#ifndef FS_UTILS_H
#define FS_UTILS_H

#include <string>

/// @ingroup utils
namespace utils {

/**
 * @brief Получает каталог исполняемого файла.
 *
 * Использует платформозависимые механизмы (Linux/macOS)
 * для определения расположения текущего бинарного файла.
 *
 * @return Абсолютный путь к каталогу исполняемого файла.
 */
std::string getBinaryDir();

/**
 * @brief Преобразует путь в абсолютный относительно каталога бинарного файла.
 *
 * Если путь уже является абсолютным, возвращается без изменений.
 *
 * @param path Входной путь (относительный или абсолютный).
 * @return Абсолютный путь к файлу.
 */
std::string resolvePath(const std::string& path);

}  // namespace utils

#endif  // FS_UTILS_H
